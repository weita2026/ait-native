use super::*;

pub const DEFAULT_HOMEBREW_PYTHON_FORMULA: &str = "python@3";

pub fn release_formula(
    repo: &RepoRuntime,
    release_id: &str,
    name: &str,
) -> Result<JsonValue, String> {
    release_formula_with_python(repo, release_id, name, DEFAULT_HOMEBREW_PYTHON_FORMULA)
}

pub fn release_formula_with_python(
    repo: &RepoRuntime,
    release_id: &str,
    name: &str,
    python_formula: &str,
) -> Result<JsonValue, String> {
    let python_formula = require_homebrew_formula_name(python_formula)?;
    let record = get_release_candidate(repo, release_id)?;
    let artifacts = record
        .get("artifacts")
        .and_then(JsonValue::as_array)
        .cloned()
        .unwrap_or_default();
    let wheel = artifacts
        .iter()
        .find(|row| string_field(row, "kind").as_deref() == Some("wheel"))
        .cloned()
        .ok_or_else(|| {
            format!("Release {release_id} does not have a wheel artifact yet. Run `ait release build {release_id}` first.")
        })?;
    let package = record
        .get("package")
        .and_then(JsonValue::as_object)
        .cloned()
        .unwrap_or_default();
    let scripts = package
        .get("scripts")
        .and_then(JsonValue::as_object)
        .cloned()
        .unwrap_or_default();
    let script_names = scripts.keys().cloned().collect::<Vec<_>>();
    let formula_path = repo
        .workspace_root()
        .join("dist")
        .join(format!("{name}.rb"));
    fs::create_dir_all(formula_path.parent().unwrap()).map_err(io_error)?;
    let homepage = package_homepage(&package, &required_string_field(&record, "repo_name")?);
    let license_literal = homebrew_license_literal(
        package
            .get("license")
            .and_then(JsonValue::as_str)
            .unwrap_or_default(),
    );
    let wheel_filename = artifact_download_name(&wheel)?;
    let mut symlink_lines = script_names
        .iter()
        .map(|script| format!("    bin.install_symlink libexec/\"bin/{script}\""))
        .collect::<Vec<_>>()
        .join("\n");
    if symlink_lines.is_empty() {
        symlink_lines =
            "    odie \"Formula generated without any console scripts to link.\"".to_string();
    }
    let formula_text = format!(
        "class {} < Formula\n  preserve_rpath\n\n  desc {}\n  homepage {}\n  url {}\n  sha256 {}\n  license {}\n\n  depends_on \"{}\"\n\n  def install\n    system Formula[\"{}\"].opt_bin/\"python3\", \"-m\", \"venv\", libexec\n    wheel = buildpath/{}\n    cp cached_download, wheel\n    system libexec/\"bin/python\", \"-m\", \"pip\", \"install\", wheel\n{}\n  end\n\n  def caveats\n    <<~EOS\n      Homebrew tap formula generated by `ait release formula`.\n      Expected console scripts from this package: {}.\n      This draft intentionally avoids auto-starting services.\n      `ait-server` still requires self-hosted runtime configuration.\n    EOS\n  end\nend\n",
        formula_class_name(name),
        json_quote(package.get("description").and_then(JsonValue::as_str).unwrap_or("ait release candidate")),
        json_quote(&homepage),
        json_quote(&required_string_field(&wheel, "url")?),
        json_quote(&required_string_field(&wheel, "sha256")?),
        license_literal,
        python_formula,
        python_formula,
        json_quote(&wheel_filename),
        symlink_lines,
        if script_names.is_empty() { "none".to_string() } else { script_names.join(", ") },
    );
    fs::write(&formula_path, formula_text).map_err(io_error)?;
    let mut updated_artifacts = artifacts;
    updated_artifacts.retain(|row| string_field(row, "kind").as_deref() != Some("formula"));
    updated_artifacts.push(artifact_info(repo, &formula_path)?);
    updated_artifacts.sort_by_key(|row| required_string_field(row, "kind").unwrap_or_default());
    let formula = json!({
        "name": name,
        "class_name": formula_class_name(name),
        "path": relative_or_absolute(repo, &formula_path),
        "artifact_kind": "wheel",
        "homepage": homepage,
        "license": package.get("license").cloned().unwrap_or(JsonValue::String(String::new())),
        "url": wheel.get("url").cloned().unwrap_or(JsonValue::Null),
        "sha256": wheel.get("sha256").cloned().unwrap_or(JsonValue::Null),
        "wheel_filename": wheel_filename,
    });
    let mut metadata = record
        .get("metadata")
        .and_then(JsonValue::as_object)
        .cloned()
        .unwrap_or_default();
    metadata.insert("formula".to_string(), formula.clone());
    update_release(
        repo,
        release_id,
        None,
        None,
        Some(JsonValue::Array(updated_artifacts)),
        Some(formula),
        Some(JsonValue::Object(metadata)),
    )?;
    get_release_candidate(repo, release_id)
}

fn require_homebrew_formula_name(value: &str) -> Result<&str, String> {
    if value.is_empty()
        || value.trim() != value
        || value.len() > 128
        || !value.chars().all(|character| {
            character.is_ascii_alphanumeric() || matches!(character, '@' | '+' | '-' | '.' | '_')
        })
    {
        return Err(
            "--python-formula must be a bounded Homebrew formula name without whitespace or path separators."
                .to_string(),
        );
    }
    Ok(value)
}

impl ReleaseProfile {
    pub(super) fn to_json(&self) -> JsonValue {
        json!({
            "required_scripts": self.required_scripts,
            "forbidden_scripts": self.forbidden_scripts,
            "release_docs": self.release_docs,
            "license_files": self.license_files,
            "contributor_files": self.contributor_files,
            "quickstart_files": self.quickstart_files,
            "excluded_paths": self.excluded_paths,
            "setuptools_package_excludes": self.setuptools_package_excludes,
        })
    }

    pub(super) fn requires_package_metadata(&self) -> bool {
        !self.license.is_empty()
            || !self.keywords.is_empty()
            || !self.classifiers.is_empty()
            || !self.required_package_urls.is_empty()
            || self.readme_file.is_some()
    }
}

