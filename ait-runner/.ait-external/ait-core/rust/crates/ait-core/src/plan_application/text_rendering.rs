use super::*;

pub(super) fn render_plan_items_payload_json(payload: &PlanItemsPayload) -> JsonValue {
    JsonValue::Object(JsonMap::from_iter([
        (
            "plan_id".to_string(),
            json_optional_string(payload.plan_id.as_deref()),
        ),
        (
            "plan_title".to_string(),
            json_optional_string(payload.plan_title.as_deref()),
        ),
        (
            "plan_revision_id".to_string(),
            json_optional_string(payload.plan_revision_id.as_deref()),
        ),
        (
            "revision_number".to_string(),
            json_optional_i64(payload.revision_number),
        ),
        (
            "identity_only".to_string(),
            JsonValue::Bool(payload.identity_only),
        ),
        (
            "dispatch_validation_required".to_string(),
            JsonValue::Bool(payload.dispatch_validation_required),
        ),
        (
            "dispatch_validation_hint".to_string(),
            JsonValue::String(payload.dispatch_validation_hint.clone()),
        ),
        ("item_count".to_string(), json_usize(payload.item_count)),
        (
            "items".to_string(),
            JsonValue::Array(
                payload
                    .items
                    .iter()
                    .map(render_dispatch_plan_item_json)
                    .collect(),
            ),
        ),
    ]))
}

