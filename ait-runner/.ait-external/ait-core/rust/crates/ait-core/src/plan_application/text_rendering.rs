pub(super) fn render_dispatch_summary_item_json(payload: &DispatchSummaryItem) -> JsonValue {
    JsonValue::Object(JsonMap::from_iter([
        (
            "plan_item_ref".to_string(),
            json_optional_string(payload.plan_item_ref.as_deref()),
        ),
        ("text".to_string(), JsonValue::String(payload.text.clone())),
        (
            "checkbox_state".to_string(),
            JsonValue::String(payload.checkbox_state.clone()),
        ),
        (
            "heading_path".to_string(),
            JsonValue::Array(
                payload
                    .heading_path
                    .iter()
                    .map(|value| JsonValue::String(value.clone()))
                    .collect(),
            ),
        ),
        (
            "line_number".to_string(),
            JsonValue::Number(payload.line_number.into()),
        ),
        (
            "linked_tasks".to_string(),
            JsonValue::Array(
                payload
                    .linked_tasks
                    .iter()
                    .map(render_linked_task_summary_json)
                    .collect(),
            ),
        ),
        ("taskable".to_string(), JsonValue::Bool(payload.taskable)),
        (
            "taskable_blocker".to_string(),
            json_optional_string(payload.taskable_blocker.as_deref()),
        ),
    ]))
}

